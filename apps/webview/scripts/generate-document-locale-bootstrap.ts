import {mkdir, readFile, writeFile} from 'node:fs/promises'
import {dirname, join} from 'node:path'
import {fileURLToPath} from 'node:url'

import {selectableLanguageDefinitions} from '../src/i18n/language-availability'

const __dirname = dirname(fileURLToPath(import.meta.url))
const outputPath = join(__dirname, '../src/assets/bootstrap/document-locale.js')
const isCheck = process.argv.includes('--check')

const languageDirections = Object.fromEntries(
  selectableLanguageDefinitions.map(({code, direction}) => [code, direction]),
)

const generatedSource = `/* Generated by scripts/generate-document-locale-bootstrap.ts. Do not edit. */
(function applyPersistedDocumentLocale() {
  'use strict'

  var fallbackLanguage = 'en'
  var directions = ${JSON.stringify(languageDirections)}
  var persistedLanguage = null

  try {
    persistedLanguage = window.localStorage.getItem('current-lang')
  } catch (_error) {
    persistedLanguage = null
  }

  var language = Object.prototype.hasOwnProperty.call(directions, persistedLanguage)
    ? persistedLanguage
    : fallbackLanguage

  document.documentElement.lang = language
  document.documentElement.dir = directions[language] || 'ltr'
})()
`

const main = async (): Promise<void> => {
  if (isCheck) {
    let current = ''
    try {
      current = await readFile(outputPath, 'utf8')
    } catch {
      throw new Error('Document locale bootstrap is missing. Run bun run generate:document-locale-bootstrap.')
    }

    if (current !== generatedSource) {
      throw new Error('Document locale bootstrap is stale. Run bun run generate:document-locale-bootstrap.')
    }
    return
  }

  await mkdir(dirname(outputPath), {recursive: true})
  await writeFile(outputPath, generatedSource)
}

await main()
