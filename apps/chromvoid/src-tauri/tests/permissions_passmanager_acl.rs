#[test]
fn native_edge_back_command_is_manifested_and_allowed_for_mobile() {
    assert!(
        BUILD_RS.contains("\"configure_native_edge_back\""),
        "build.rs command manifest must include configure_native_edge_back"
    );
    assert!(
        NATIVE_EDGE_BACK_PERMISSION.contains("allow-configure-native-edge-back"),
        "autogenerated permissions must include allow-configure-native-edge-back"
    );

    let mobile = set_block("mobile");
    assert!(
        mobile.contains("allow-configure-native-edge-back"),
        "mobile set must allow configure_native_edge_back"
    );
    assert!(
        !mobile.contains("allow-setup-native-gestures"),
        "retired setup_native_gestures permission must not remain in the mobile set"
    );
}

#[test]
fn credential_provider_commands_are_manifested_and_allowed_for_desktop_and_mobile() {
    let commands = [
        "credential_provider_status",
        "open_credential_provider_settings",
        "credential_provider_passkeys_list",
        "credential_provider_passkey_delete",
    ];
    let permissions = [
        "allow-credential-provider-status",
        "allow-open-credential-provider-settings",
        "allow-credential-provider-passkeys-list",
        "allow-credential-provider-passkey-delete",
    ];

    for command in commands {
        assert!(
            BUILD_RS.contains(&format!("\"{command}\"")),
            "build.rs command manifest must include {command}"
        );
    }

    for identifier in ["desktop", "mobile"] {
        let permission_set = set_block(identifier);
        assert!(
            !permission_set.is_empty(),
            "{identifier} permission set not found in permissions/app.toml"
        );
        for permission in permissions {
            assert!(
                permission_set.contains(permission),
                "{identifier} set must include {permission}"
            );
        }
    }

    let desktop = set_block("desktop");
    let mobile = set_block("mobile");
    for legacy_permission in [
        "allow-android-passkeys-list",
        "allow-android-passkey-delete",
    ] {
        assert!(
            !desktop.contains(legacy_permission),
            "desktop must use the generic Credential Provider permission instead of {legacy_permission}"
        );
        assert!(
            mobile.contains(legacy_permission),
            "mobile must retain {legacy_permission} for Android compatibility"
        );
    }
}

