#[test]
fn ssh_keygen_command_is_manifested_and_allowed_for_mobile() {
    assert!(
        BUILD_RS.contains("\"ssh_keygen\""),
        "build.rs command manifest must include ssh_keygen"
    );
    assert!(
        SSH_KEYGEN_PERMISSION.contains("allow-ssh-keygen"),
        "autogenerated permissions must include allow-ssh-keygen"
    );

    let mobile = set_block("mobile");
    assert!(
        !mobile.is_empty(),
        "mobile permission set not found in permissions/app.toml"
    );
    assert!(
        mobile.contains("allow-ssh-keygen"),
        "mobile set must include allow-ssh-keygen"
    );
    assert!(
        mobile_invoke_handler().contains("ssh_keygen::ssh_keygen"),
        "mobile invoke handler must register ssh_keygen"
    );
    assert!(
        !LIB_RS.contains("#[cfg(desktop)]\nmod ssh_keygen;"),
        "ssh_keygen module must compile for mobile targets"
    );
}

