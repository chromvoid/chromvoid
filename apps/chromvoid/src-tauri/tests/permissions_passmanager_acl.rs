const APP_PERMISSIONS: &str = include_str!("../permissions/app.toml");
const BUILD_RS: &str = include_str!("../build.rs");
const LIB_RS: &str = include_str!("../src/lib.rs");
const CATALOG_DOWNLOAD_RANGE_PERMISSION: &str =
    include_str!("../permissions/autogenerated/catalog_download_range.toml");
const PASSWORD_STRENGTH_PERMISSION: &str =
    include_str!("../permissions/autogenerated/password_strength_estimate.toml");
const MOBILE_USB_DETECT_PERMISSION: &str =
    include_str!("../permissions/autogenerated/mobile_usb_detect.toml");
const NATIVE_EDGE_BACK_PERMISSION: &str =
    include_str!("../permissions/autogenerated/configure_native_edge_back.toml");
const SSH_KEYGEN_PERMISSION: &str = include_str!("../permissions/autogenerated/ssh_keygen.toml");

fn set_block(identifier: &str) -> String {
    APP_PERMISSIONS
        .split("[[set]]")
        .find(|block| block.contains(&format!("identifier = \"{identifier}\"")))
        .map(str::to_string)
        .unwrap_or_default()
}

fn mobile_invoke_handler() -> &'static str {
    let (_, handler) = LIB_RS
        .split_once("#[cfg(mobile)]\n    let builder = builder.invoke_handler")
        .expect("mobile invoke handler must exist in src/lib.rs");
    handler
        .split_once("]);")
        .map(|(commands, _)| commands)
        .expect("mobile invoke handler must terminate with ]);")
}

#[test]
fn desktop_permission_set_allows_passmanager_stream_commands() {
    let desktop = set_block("desktop");
    assert!(
        !desktop.is_empty(),
        "desktop permission set not found in permissions/app.toml"
    );

    for permission in [
        "allow-passmanager-upload-chunk",
        "allow-passmanager-download",
        "allow-passmanager-secret-read",
        "allow-passmanager-secret-write-chunk",
    ] {
        assert!(
            desktop.contains(permission),
            "desktop set must include {permission}"
        );
    }
}

